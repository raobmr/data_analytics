def subgroup_metrics(df_meta, y_true, y_pred, y_prob, group_col):
    """Compute TPR, FPR, Precision, Recall, F1, AUC by subgroup."""
    records = []
    for g in df_meta[group_col].dropna().unique():
        idx = (df_meta[group_col] == g).values
        if idx.sum() < 30:
            continue
        yt  = y_true[idx]
        yp  = y_pred[idx]
        ypr = y_prob[idx]

        tn, fp, fn, tp = confusion_matrix(yt, yp, labels=[0, 1]).ravel()
        tpr  = tp / (tp + fn + 1e-9)
        fpr  = fp / (fp + tn + 1e-9)
        prec = tp / (tp + fp + 1e-9)
        rec  = tpr
        f1   = 2 * prec * rec / (prec + rec + 1e-9)
        auc  = roc_auc_score(yt, ypr) if len(set(yt)) > 1 else float("nan")
        fn_rate = fn / (fn + tp + 1e-9)

        records.append({
            "group": g, "n": int(idx.sum()),
            "TPR":  round(tpr,  4), "FPR": round(fpr, 4),
            "Precision": round(prec, 4), "Recall": round(rec, 4),
            "F1":  round(f1,   4), "AUC": round(auc, 4),
            "FN_rate": round(fn_rate, 4),
            "TP": int(tp), "FP": int(fp), "FN": int(fn), "TN": int(tn)
        })
    return pd.DataFrame(records).sort_values("AUC", ascending=False)


