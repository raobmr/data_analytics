def run_experiment(exp_name, toggles, df_raw_in, baseline_results, n_splits=5):
    """Run one experiment with given feature toggles; log results."""
    t0 = time.time()

    # Build features
    df_exp, new_feats = add_feature_block(df_raw_in, toggles)

    # Fill missing, encode cats
    df_exp2 = prepare_baseline(df_exp)

    active_features = [c for c in feat_cols if c in df_exp2.columns] + \
                      [f for f in new_feats if f in df_exp2.columns]
    # Deduplicate
    active_features = list(dict.fromkeys(active_features))

    X = df_exp2[active_features].fillna(0).values
    y_exp = df_exp2[SCHEMA["target"]].values # Changed "target" to SCHEMA["target"]

    skf_ = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)
    model = GradientBoostingClassifier(n_estimators=100, random_state=42)

    auc_scores = cross_val_score(model, X, y_exp, cv=skf_, scoring="roc_auc")
    f1_scores  = cross_val_score(model, X, y_exp, cv=skf_, scoring="f1")

    delta_auc = auc_scores.mean() - baseline_results["auc_mean"]
    delta_f1  = f1_scores.mean()  - baseline_results["f1_mean"]

    result = {
        "experiment": exp_name,
        "timestamp": datetime.now().isoformat(),
        "toggles": {k: v for k, v in toggles.items() if v},
        "n_features": len(active_features),
        "new_features": new_feats,
        "auc_mean": round(auc_scores.mean(), 5),
        "auc_std":  round(auc_scores.std(), 5),
        "f1_mean":  round(f1_scores.mean(), 5),
        "f1_std":   round(f1_scores.std(), 5),
        "delta_auc": round(delta_auc, 5),
        "delta_f1":  round(delta_f1, 5),
        "runtime_s": round(time.time() - t0, 2),
        "auc_cv": [round(x, 5) for x in auc_scores.tolist()]
    }
    EXPERIMENT_LOG.append(result)

    # Register each new feature
    for feat in new_feats:
        if feat not in FEATURE_REGISTRY:
            FEATURE_REGISTRY[feat] = {
                "first_seen": exp_name,
                "delta_auc_history": [],
                "stable": None
            }
        FEATURE_REGISTRY[feat]["delta_auc_history"].append(delta_auc)

    return result

