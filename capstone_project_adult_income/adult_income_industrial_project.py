def add_feature_block(df_in, toggles=None):
    """
    Add engineered features to the dataframe.

    Parameters
    ----------
    df_in : pd.DataFrame
        Preprocessed dataframe (fnlwgt already excluded).
    toggles : dict
        Feature toggles. Each key maps to True/False.
        Defaults: all features ON.

    Returns
    -------
    df_out : pd.DataFrame
        Dataframe with added feature columns.
    new_features : list
        Names of added feature columns.
    """
    DEFAULT_TOGGLES = {
        "USE_AGE_BINS":       True,
        "USE_CAPITAL_NET":    True,
        "USE_CAPITAL_FLAG":   True,
        "USE_HOURS_CATEGORY": True,
        "USE_EDU_HOURS":      True,
        "USE_MARITAL_BINARY": True,
        "USE_HIGH_EDU_FLAG":  True,
    }
    if toggles is None:
        toggles = DEFAULT_TOGGLES
    else:
        toggles = {**DEFAULT_TOGGLES, **toggles}

    df_out = df_in.copy()
    new_features = []

    # F1 — Age bins (life-stage encoding)
    if toggles.get("USE_AGE_BINS", True):
        bins   = [0, 24, 34, 49, 64, 120]
        labels = [0, 1, 2, 3, 4]          # ordinal life stage
        df_out["age_bins"] = pd.cut(df_out["age"], bins=bins, labels=labels).astype(float)
        new_features.append("age_bins")

    # F2 — Net capital (gain - loss)
    if toggles.get("USE_CAPITAL_NET", True):
        df_out["capital_net"] = df_out["capital_gain"] - df_out["capital_loss"]
        new_features.append("capital_net")

    # F3 — Binary capital activity flag
    if toggles.get("USE_CAPITAL_FLAG", True):
        df_out["has_capital_activity"] = (
            (df_out["capital_gain"] > 0) | (df_out["capital_loss"] > 0)
        ).astype(int)
        new_features.append("has_capital_activity")

    # F4 — Hours category (ordinal binning)
    if toggles.get("USE_HOURS_CATEGORY", True):
        def hour_cat(h):
            if h < 35: return 0    # Part-time
            elif h <= 45: return 1 # Standard
            elif h <= 60: return 2 # Overtime
            else: return 3         # Extreme
        df_out["hours_category"] = df_out["hours_per_week"].apply(hour_cat)
        new_features.append("hours_category")

    # F5 — Education × Hours interaction
    if toggles.get("USE_EDU_HOURS", True):
        df_out["edu_hours_interaction"] = df_out["educational_num"] * df_out["hours_per_week"]
        new_features.append("edu_hours_interaction")

    # F6 — Marital binary (is_married)
    if toggles.get("USE_MARITAL_BINARY", True):
        if "marital_status" in df_out.columns:
            married_vals = {"Married-civ-spouse", "Married-AF-spouse"}
            df_out["is_married"] = df_out["marital_status"].isin(married_vals).astype(int)
        else:
            # Already label-encoded — skip gracefully
            df_out["is_married"] = 0
        new_features.append("is_married")

    # F7 — High education flag
    if toggles.get("USE_HIGH_EDU_FLAG", True):
        df_out["is_high_edu"] = (df_out["educational_num"] >= 13).astype(int)
        new_features.append("is_high_edu")

    return df_out, new_features

