def add_fn_features(df_in, toggles=None):
    """
    Add false-negative–reduction features to the dataframe.

    Parameters
    ----------
    df_in   : pd.DataFrame  — preprocessed dataframe (fnlwgt excluded).
    toggles : dict          — feature on/off switches; defaults: all ON.

    Returns
    -------
    df_out      : pd.DataFrame  — extended dataframe
    new_features: list[str]     — names of added columns
    """
    DEFAULT_TOGGLES = {
        "USE_HIGH_CAPITAL_FLAG": True,
        "USE_EXEC_MGR_FLAG":     True,
        "USE_MARRIED_EDU":       True,
        "USE_AGE_EDU":           True,
        "USE_OVERTIME_PRO":      True,
        "USE_PRIVATE_FLAG":      True,
    }
    if toggles is None:
        toggles = DEFAULT_TOGGLES
    else:
        toggles = {**DEFAULT_TOGGLES, **toggles}

    df_out = df_in.copy()
    new_features = []

    # B1 — High capital gain binary flag
    if toggles.get("USE_HIGH_CAPITAL_FLAG", True):
        df_out["high_capital_gain_flag"] = (
            pd.to_numeric(df_out["capital_gain"], errors="coerce").fillna(0) > 5000
        ).astype(int)
        new_features.append("high_capital_gain_flag")

    # B2 — Executive / managerial role flag
    if toggles.get("USE_EXEC_MGR_FLAG", True):
        if "occupation" in df_out.columns:
            exec_occ = {"Exec-managerial", "Prof-specialty"}
            df_out["exec_managerial_flag"] = df_out["occupation"].isin(exec_occ).astype(int)
        else:
            df_out["exec_managerial_flag"] = 0
        new_features.append("exec_managerial_flag")

    # B3 — Married × Education interaction
    if toggles.get("USE_MARRIED_EDU", True):
        married_vals = {"Married-civ-spouse", "Married-AF-spouse"}
        if "marital_status" in df_out.columns:
            is_married = df_out["marital_status"].isin(married_vals).astype(int)
        else:
            is_married = df_out.get("is_married", pd.Series(0, index=df_out.index))
        edu_num = pd.to_numeric(df_out.get("educational_num", df_out.get("educational_num", 0)),
                                errors="coerce").fillna(0)
        df_out["married_highEdu_interaction"] = is_married * edu_num
        new_features.append("married_highEdu_interaction")

    # B4 — Age × Education interaction
    if toggles.get("USE_AGE_EDU", True):
        age = pd.to_numeric(df_out["age"], errors="coerce").fillna(df_out["age"].median())
        edu_num = pd.to_numeric(df_out.get("educational_num", df_out.get("educational_num", 0)),
                                errors="coerce").fillna(0)
        df_out["age_edu_interaction"] = age * edu_num
        new_features.append("age_edu_interaction")

    # B5 — Overtime professional composite flag
    if toggles.get("USE_OVERTIME_PRO", True):
        hrs = pd.to_numeric(df_out["hours_per_week"], errors="coerce").fillna(0)
        if "occupation" in df_out.columns:
            pro_occ = {"Exec-managerial", "Prof-specialty", "Tech-support"}
            is_pro = df_out["occupation"].isin(pro_occ).astype(int)
        else:
            is_pro = pd.Series(0, index=df_out.index)
        df_out["overtime_professional_flag"] = ((hrs > 45) & (is_pro == 1)).astype(int)
        new_features.append("overtime_professional_flag")

    # B6 — Private sector flag
    if toggles.get("USE_PRIVATE_FLAG", True):
        if "workclass" in df_out.columns:
            df_out["private_sector_flag"] = (df_out["workclass"] == "Private").astype(int)
        else:
            df_out["private_sector_flag"] = 0
        new_features.append("private_sector_flag")

    return df_out, new_features


