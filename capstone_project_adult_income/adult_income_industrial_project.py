def run_recall_experiment(exp_name, toggles_a, toggles_b, df_raw_in,
                          baseline_results, n_splits=5):
    """
    Evaluate with recall as primary metric alongside AUC and F1.
    Stores results in EXPERIMENT_LOG and FEATURE_REGISTRY.
    """
    t0 = time.time()
    df_exp, new_feats = add_all_features(df_raw_in, toggles_a, toggles_b)
    df_exp2 = prepare_baseline(df_exp)

    base_feats = [c for c in feat_cols if c in df_exp2.columns]
    eng_feats  = [f for f in new_feats if f in df_exp2.columns]
    active_features = list(dict.fromkeys(base_feats + eng_feats))

    X = df_exp2[active_features].fillna(0).values
    y_exp = df_exp2[SCHEMA["target"]].values

    skf_ = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)
    model = GradientBoostingClassifier(n_estimators=100, random_state=42)

    scoring = {"auc": "roc_auc", "f1": "f1", "recall": "recall", "precision": "precision"}
    cv_res = cross_validate(model, X, y_exp, cv=skf_, scoring=scoring)

    auc_scores = cv_res["test_auc"]
    f1_scores  = cv_res["test_f1"]
    rec_scores = cv_res["test_recall"]
    pre_scores = cv_res["test_precision"]

    delta_auc    = auc_scores.mean() - baseline_results["auc_mean"]
    delta_f1     = f1_scores.mean()  - baseline_results["f1_mean"]
    delta_recall = rec_scores.mean() - baseline_results.get("recall_mean", rec_scores.mean())

    result = {
        "experiment": exp_name,
        "timestamp": datetime.now().isoformat(),
        "phase": "B",
        "n_features": len(active_features),
        "new_features": new_feats,
        "auc_mean":       round(auc_scores.mean().item(), 5),
        "auc_std":        round(auc_scores.std().item(),  5),
        "f1_mean":        round(f1_scores.mean().item(),  5),
        "f1_std":         round(f1_scores.std().item(),   5),
        "recall_mean":    round(rec_scores.mean().item(), 5),
        "recall_std":     round(rec_scores.std().item(),  5),
        "precision_mean": round(pre_scores.mean().item(), 5),
        "delta_auc":      round(delta_auc.item(),    5),
        "delta_f1":       round(delta_f1.item(),     5),
        "delta_recall":   round(delta_recall.item(), 5),
        "runtime_s":      round(time.time() - t0, 2),
        "recall_cv": [round(x, 5) for x in rec_scores.tolist()],
        "auc_cv":    [round(x, 5) for x in auc_scores.tolist()],
    }
    EXPERIMENT_LOG.append(result)

    # Update feature registry
    for feat in new_feats:
        if feat not in FEATURE_REGISTRY:
            FEATURE_REGISTRY[feat] = {
                "first_seen": exp_name,
                "delta_auc_history":    [],
                "delta_recall_history": [],
                "stable": None,
                "rejected": False,
                "rejection_reason": None
            }
        if "delta_recall_history" not in FEATURE_REGISTRY[feat]:
          FEATURE_REGISTRY[feat]["delta_recall_history"] = []
        FEATURE_REGISTRY[feat]["delta_auc_history"].append(float(delta_auc))
        FEATURE_REGISTRY[feat]["delta_recall_history"].append(float(delta_recall))

    return result


